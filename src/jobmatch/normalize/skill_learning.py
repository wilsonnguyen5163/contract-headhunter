"""Learn skills from the contractor list: every core strength the curated taxonomy does not
recognize becomes a skill of its own (category "learned"), so a job that mentions the same
phrase gets tagged with it and skill overlap counts. Rules in config/skill_learning.yaml keep
out phrases too short or generic to match job text safely.

Learned skills are not merged with synonyms ("gtm advisory" and "go-to-market" stay apart),
so each comes with the closest curated skill as a suggestion for a person to merge into
config/skills_taxonomy.yaml. Profile text is personal data: only strength phrases and counts
are written, never names.
"""

from collections import Counter
from collections.abc import Iterable
from pathlib import Path

import yaml
from pydantic import BaseModel
from rapidfuzz import fuzz, process

from jobmatch.config import SkillsTaxonomy, StrictModel
from jobmatch.normalize.phrases import fold
from jobmatch.normalize.skills import SkillExtractor
from jobmatch.schemas import ContractorProfile
from jobmatch.storage.files import atomic_write_text

SKILL_LEARNING_FILE = "skill_learning.yaml"
LEARNED_CATEGORY = "learned"


class SkillLearningRules(StrictModel):
    version: int
    min_words: int
    max_words: int
    acronyms: list[str]
    stopwords: list[str]
    suggest_threshold: float


class SkillSuggestion(BaseModel):
    phrase: str
    contractors: int  # how many contractors list it
    closest_skill: str | None
    closest_term: str | None  # the curated name or alias it resembles
    similarity: float | None


class LearnReport(BaseModel):
    phrases: int  # distinct strength phrases
    known: int  # already recognized by the curated taxonomy
    learned: int
    skipped: int  # too short, too long or generic


def load_skill_learning(config_dir: Path) -> SkillLearningRules:
    with (config_dir / SKILL_LEARNING_FILE).open(encoding="utf-8") as f:
        return SkillLearningRules.model_validate(yaml.safe_load(f))


def _phrase(text: str) -> str:
    return " ".join(text.casefold().split()).strip(" .;,")


def learnable(phrase: str, rules: SkillLearningRules) -> bool:
    if fold(phrase) in {fold(w) for w in rules.stopwords}:
        return False
    words = len(phrase.split())
    if words > rules.max_words:
        return False
    return words >= rules.min_words or fold(phrase) in {fold(a) for a in rules.acronyms}


def learn_skills(
    profiles: Iterable[ContractorProfile], curated: SkillsTaxonomy, rules: SkillLearningRules
) -> tuple[SkillsTaxonomy, list[SkillSuggestion], LearnReport]:
    extractor = SkillExtractor(curated)
    counts: Counter[str] = Counter()
    for profile in profiles:
        for strength in dict.fromkeys(_phrase(s) for s in profile.core_strengths):
            if strength:
                counts[strength] += 1

    terms = {
        term.casefold(): name
        for name, entry in curated.skills.items()
        for term in (name, *entry.aliases)
    }
    learned: dict[str, dict[str, object]] = {}
    seen: set[str] = set()  # accent-folded, so "rédaction" and "redaction" are one skill
    suggestions: list[SkillSuggestion] = []
    known = skipped = 0
    for phrase, n in sorted(counts.items()):
        if extractor.extract(phrase):
            known += 1
            continue
        if not learnable(phrase, rules) or fold(phrase) in seen:
            skipped += 1
            continue
        seen.add(fold(phrase))
        learned[phrase] = {"category": LEARNED_CATEGORY, "aliases": []}
        best = process.extractOne(phrase, list(terms), scorer=fuzz.token_sort_ratio)
        close = best is not None and best[1] >= rules.suggest_threshold
        suggestions.append(
            SkillSuggestion(
                phrase=phrase,
                contractors=n,
                closest_skill=terms[best[0]] if close and best else None,
                closest_term=best[0] if close and best else None,
                similarity=round(best[1], 1) if close and best else None,
            )
        )
    taxonomy = SkillsTaxonomy.model_validate({"version": 1, "skills": learned})
    report = LearnReport(phrases=len(counts), known=known, learned=len(learned), skipped=skipped)
    return taxonomy, suggestions, report


def write_learned(taxonomy: SkillsTaxonomy, path: Path) -> None:
    header = (
        "# Generated by build-contractors from the contractor list. Do not edit: it is rewritten\n"
        "# on every build. To curate a skill, add it to config/skills_taxonomy.yaml (curated\n"
        "# terms always win) and it drops out of this file on the next build.\n"
    )
    body = yaml.safe_dump(taxonomy.model_dump(), sort_keys=True, allow_unicode=True)
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(path, header + body)
